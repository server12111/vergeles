type Params = Promise<{ doc: string }>;

export function generateStaticParams() {
  return Object.keys(docs).map((doc) => ({ doc }));
}

export async function generateMetadata({ params }: { params: Params }): Promise<Metadata> {
  const { doc } = await params;
  const d = docs[doc];
  return d ? { title: d.title, alternates: { canonical: `/legal/${doc}` } } : {};
}

export default async function LegalPage({ params }: { params: Params }) {
  const { doc } = await params;
  const d = docs[doc];
  if (!d) notFound();

  return (
    <article className="container-x pb-24 pt-6 md:pb-36 md:pt-10">
      <Breadcrumbs items={[{ label: d.title }]} />
      <div className="mt-10 grid gap-10 md:mt-16 md:grid-cols-12 md:gap-6">
        <header className="md:col-span-4">
          <h1 className="h-sub">{d.title}</h1>
          <p className="mt-4 text-[12px] text-muted">Редакция от {d.updated}</p>
        </header>
        <div className="max-w-2xl md:col-span-7 md:col-start-6">
          {d.sections.map((s) => (
            <section key={s.h} className="border-t border-line py-8">
              <h2 className="text-[15px] font-medium">{s.h}</h2>
              {s.p.map((p) => (
                <p key={p.slice(0, 30)} className="mt-3 text-[15px] leading-[1.7] text-graphite">
                  {p}
                </p>
              ))}
            </section>
          ))}
        </div>
      </div>
    </article>
  );
}
